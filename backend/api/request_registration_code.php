<?php
declare(strict_types=1);

require_once dirname(__DIR__) . '/bootstrap.php';
require_once dirname(__DIR__) . '/helpers/email.php';

header('Content-Type: application/json; charset=utf-8');
header('Cache-Control: no-store');

function respond(int $status, string $message): never {
    http_response_code($status);
    echo json_encode(['success' => $status === 200, 'message' => $message]);
    exit;
}

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    header('Allow: POST');
    respond(405, 'Method not allowed.');
}
if (!empty($_SESSION['user_id'])) {
    respond(403, 'Sign out before creating another account.');
}

// A token is generated by the registration page and saved in the user's session.
$submittedToken = (string)($_POST['csrf_token'] ?? '');
if ($submittedToken === '' || !hash_equals((string)($_SESSION['registration_csrf'] ?? ''), $submittedToken)) {
    respond(403, 'Please reload the registration page and try again.');
}

$studentNumber = trim((string)($_POST['student_number'] ?? ''));
$lastName = trim((string)($_POST['last_name'] ?? ''));
$dateOfBirth = trim((string)($_POST['date_of_birth'] ?? ''));
if ($studentNumber === '' || strlen($studentNumber) > 50 || $lastName === '' || strlen($lastName) > 100 ||
    !preg_match('/^\d{4}-\d{2}-\d{2}$/', $dateOfBirth)) {
    respond(422, 'Enter a valid student number, surname, and birth date.');
}

// Limit requests per browser session. A server-side IP limiter is recommended for deployment.
$now = time();
$history = array_values(array_filter($_SESSION['registration_requests'] ?? [], static fn($time) => is_int($time) && $time > $now - 3600));
if (count($history) >= 8) {
    respond(429, 'Too many requests. Please try again later.');
}
$history[] = $now;
$_SESSION['registration_requests'] = $history;

// Uniform response to avoid exposing which student records exist.
$generic = 'If your details match an eligible record, a verification code will be sent to the email on file.';

try {
    $stmt = $conn->prepare('SELECT m.masterlist_id, m.email, m.registration_status, m.user_id
        FROM student_masterlist m
        WHERE m.student_number = ? AND LOWER(TRIM(m.last_name)) = LOWER(?) AND m.date_of_birth = ?
        LIMIT 1');
    $stmt->bind_param('sss', $studentNumber, $lastName, $dateOfBirth);
    $stmt->execute();
    $master = $stmt->get_result()->fetch_assoc();
    $stmt->close();

    if (!$master) {
    error_log('CMU Registration: Masterlist record not found.');
    respond(200, $generic);
    }

    if ($master['registration_status'] !== 'UNREGISTERED') {
        error_log('CMU Registration: Student is not marked UNREGISTERED.');
        respond(200, $generic);
    }

    if ($master['user_id'] !== null) {
        error_log('CMU Registration: Student already linked to an account.');
        respond(200, $generic);
    }

    error_log('CMU Registration: Masterlist eligibility passed.');

    $stmt = $conn->prepare('SELECT 1 FROM users WHERE account_number = ? LIMIT 1');
    $stmt->bind_param('s', $studentNumber);
    $stmt->execute();
    $accountExists = (bool)$stmt->get_result()->fetch_row();
    $stmt->close();
    if ($accountExists) respond(200, $generic);

    $stmt = $conn->prepare('SELECT 1 FROM students WHERE student_number = ? OR email = ? LIMIT 1');
    $stmt->bind_param('ss', $studentNumber, $master['email']);
    $stmt->execute();
    $studentExists = (bool)$stmt->get_result()->fetch_row();
    $stmt->close();
    if ($studentExists) respond(200, $generic);

    $id = (int)$master['masterlist_id'];
    $stmt = $conn->prepare('SELECT send_count, last_sent_at, created_at, consumed_at FROM registration_verifications WHERE masterlist_id = ?');
    $stmt->bind_param('i', $id);
    $stmt->execute();
    $prior = $stmt->get_result()->fetch_assoc();
    $stmt->close();

    if ($prior && $prior['consumed_at'] === null) {
        if (strtotime($prior['last_sent_at']) > $now - 60) respond(200, $generic);
        if (strtotime($prior['created_at']) > $now - 3600 && (int)$prior['send_count'] >= 5) respond(200, $generic);
    }

    $code = (string)random_int(100000, 999999);
    $hash = password_hash($code, PASSWORD_DEFAULT);
    $expires = date('Y-m-d H:i:s', $now + 600);
    $count = $prior && strtotime($prior['created_at']) > $now - 3600 ? (int)$prior['send_count'] + 1 : 1;

    // Send before storing. If sending fails, no valid new code is created.
    $sent = send_transactional_email(
        $master['email'],
        'CMU Enrollment System - Account Verification',
        "Your account verification code is: {$code}\n\nThis code expires in 10 minutes. If you did not request it, ignore this message."
    );
    if (!$sent) {
        error_log('Registration verification email could not be sent.');
        respond(200, $generic);
    }

    $stmt = $conn->prepare('INSERT INTO registration_verifications
        (masterlist_id, code_hash, expires_at, attempts, send_count, last_sent_at, verified_at, consumed_at, created_at)
        VALUES (?, ?, ?, 0, ?, NOW(), NULL, NULL, NOW())
        ON DUPLICATE KEY UPDATE code_hash=VALUES(code_hash), expires_at=VALUES(expires_at),
        attempts=0, send_count=VALUES(send_count), last_sent_at=NOW(), verified_at=NULL,
        consumed_at=NULL, created_at=IF(? = 1, NOW(), created_at)');
    $stmt->bind_param('issii', $id, $hash, $expires, $count, $count);
    $stmt->execute();
    $stmt->close();
    respond(200, $generic);
} catch (Throwable $exception) {
    error_log('Registration code request error: ' . $exception->getMessage());
    respond(500, 'Unable to process your request right now. Please try again later.');
}
